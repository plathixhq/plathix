<?php

declare(strict_types=1);

namespace Plathix\Modules\Preset;

/**
 * Канон формата пресета: имя файла, экранирование имён папок, список превью.
 *
 * Существует, потому что до [internal] эти три вещи жили
 * размазанными по модулю: имя файла было зашито строкой в четырёх местах
 * (upload x2, export, discovery), экранирования не было вовсе (экспорт склеивал
 * строку конкатенацией), а список допустимых превью знал только upload-пайплайн —
 * валидатор о нём не подозревал и проверял лишь отсутствие слешей.
 *
 * Любой код, читающий или пишущий формат, обязан ходить сюда, а не заводить
 * свою копию правил.
 */
final class PresetFormat
{
	/**
	 * Имя файла описания внутри пакета пресета.
	 *
	 * Двойное расширение намеренно: последний суффикс `.md` сохраняет поведение
	 * markdown для всех потребителей (WP-загрузчик и его whitelist расширений,
	 * редакторы, git-diff), а `.plx` делает файл узнаваемым в листинге.
	 */
	public const FILENAME = 'preset.plx.md';

	/**
	 * Версия грамматики файла, которую понимает этот парсер.
	 *
	 * 1 — сквозная нумерация `1.2: Folder(Name): Color(x)` ([internal] её удалил);
	 * 2 — отступы + имена в кавычках + опциональные атрибуты `{color, favorite}`.
	 *
	 * Поле `FormatVersion:` в шапке ОПЦИОНАЛЬНО: его отсутствие означает текущую
	 * версию, а не первую. Файлов с этим полем не существовало до его введения,
	 * поэтому обязательность объявила бы невалидным весь существующий корпус; а
	 * всё, что пишется руками сегодня, пишется в актуальной грамматике.
	 *
	 * Единственная функция версии — порог отказа: файл, объявивший версию выше
	 * известной, отвергается внятным сообщением вместо разбора наугад. Модель
	 * заимствована у ZIP («version needed to extract»), а не у docker-compose,
	 * где поле объявляло набор фич, разошлось с содержимым и было отменено.
	 * Повышать только при НЕСОВМЕСТИМОЙ смене грамматики: добавление поля
	 * версию не двигает, потому что неизвестные поля игнорируются.
	 */
	public const FORMAT_VERSION = 2;

	/** Допустимые имена файла превью внутри пакета. */
	public const ALLOWED_PREVIEWS = [ 'preview.webp', 'preview.png', 'preview.jpg', 'preview.jpeg' ];

	/**
	 * Оборачивает имя папки в кавычки, экранируя спецсимволы.
	 *
	 * Порядок замен значим: обратный слеш экранируется ПЕРВЫМ, иначе слеш,
	 * добавленный при экранировании кавычки, был бы экранирован повторно и
	 * round-trip перестал бы сходиться.
	 */
	public static function escape_name(string $name): string {
		$escaped = str_replace('\\', '\\\\', $name);
		$escaped = str_replace('"', '\\"', $escaped);

		return '"' . $escaped . '"';
	}

	/**
	 * Разворачивает имя из кавычек обратно в сырую строку.
	 *
	 * Возвращает null для синтаксически некорректного ввода (нет обрамляющих
	 * кавычек, незакрытая кавычка, висящий экранирующий слеш) — вызывающий код
	 * обязан превратить это в ошибку разбора, а не молча подставить обрезок.
	 *
	 * @param string $raw Значение вместе с обрамляющими кавычками.
	 */
	public static function unescape_name(string $raw): ?string {
		$length = strlen($raw);
		if ( $length < 2 || $raw[0] !== '"' || $raw[ $length - 1 ] !== '"' ) {
			return null;
		}

		$inner  = substr($raw, 1, -1);
		$result = '';
		$i      = 0;
		$len    = strlen($inner);

		while ( $i < $len ) {
			$char = $inner[ $i ];

			if ( $char !== '\\' ) {
				// Неэкранированная кавычка внутри — значит закрывающая кавычка
				// стояла раньше конца строки, и остаток не принадлежит имени.
				if ( $char === '"' ) {
					return null;
				}

				$result .= $char;
				$i++;
				continue;
			}

			// Экранирующий слеш последним символом — обрыв последовательности.
			if ( $i + 1 >= $len ) {
				return null;
			}

			$next = $inner[ $i + 1 ];
			if ( $next !== '\\' && $next !== '"' ) {
				return null;
			}

			$result .= $next;
			$i      += 2;
		}

		return $result;
	}
}
